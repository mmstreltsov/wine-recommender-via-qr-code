import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cart, config, deferred, dish, emptyCart, json, menu, rec } from '../test/fixtures'

beforeEach(() => {
  vi.resetModules()
  window.history.replaceState({}, '', '/?table=12')
})
afterEach(() => { vi.unstubAllGlobals(); window.history.replaceState({}, '', '/') })

describe('FR-33/34 AN-02 startup serialization', () => {
  it('TestFR34_AN02_failure_retry_retains_page_open_and_never_beacons_before_success', async () => {
    const first = deferred<Response>()
    const fetcher = vi.fn().mockImplementationOnce(() => first.promise).mockResolvedValue(json(menu))
    vi.stubGlobal('fetch', fetcher)
    const beacon = vi.fn(() => true)
    Object.defineProperty(navigator, 'sendBeacon', { configurable: true, value: beacon })
    const client = await import('./client')
    const tracker = await import('./tracker')
    tracker.trackPageOpen()
    tracker.trackPageOpen()
    const boot = client.ensureStarted()
    const other = client.getConfig()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(fetcher.mock.calls[0][0]).toBe('/api/v1/menu?table=12')
    window.dispatchEvent(new Event('pagehide'))
    expect(beacon).not.toHaveBeenCalled()
    first.resolve(json({ error: { message: '/private/db/password' } }, 500))
    await expect(boot).rejects.toThrow('Что-то пошло не так')
    await expect(other).rejects.toThrow('Что-то пошло не так')
    expect(fetcher).toHaveBeenCalledTimes(1)
    window.dispatchEvent(new Event('pagehide'))
    expect(beacon).not.toHaveBeenCalled()
    await client.ensureStarted()
    expect(fetcher.mock.calls[1][0]).toBe('/api/v1/menu?table=12')
    expect(beacon).toHaveBeenCalledTimes(1)
    const body = beacon.mock.calls[0] as unknown[]
    expect(body[0]).toBe('/api/v1/events')
    tracker.trackPageOpen()
    await client.ensureStarted()
    expect(beacon).toHaveBeenCalledTimes(1)
    expect(fetcher).toHaveBeenCalledTimes(2)
  })

  it.each(['abc', '0', '1000', '1e2', ' 12', '12.5'])('TestFR34_invalid_table_%s_is_omitted', async (value) => {
    window.history.replaceState({}, '', `/?table=${encodeURIComponent(value)}`)
    const fetcher = vi.fn().mockResolvedValue(json(menu))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    await client.bootstrap()
    expect(fetcher.mock.calls[0][0]).toBe('/api/v1/menu')
  })

  it('TestFR37_menu_is_refetched_not_forever_cached', async () => {
    const fetcher = vi.fn().mockImplementation(() => Promise.resolve(json(menu)))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    await client.getMenu()
    fetcher.mockResolvedValueOnce(json({ categories: [] }))
    expect(await client.getMenu()).toEqual({ categories: [] })
    expect(fetcher).toHaveBeenCalledTimes(3)
  })
})

describe('NFR-04 API boundary', () => {
  it('TestNFR04_rejects_invalid_ids_qty_and_server_payload', async () => {
    const fetcher = vi.fn().mockImplementation(() => Promise.resolve(json(menu)))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    await expect(client.getItem(NaN)).rejects.toThrow()
    expect(() => client.setItemQty(101, 21)).toThrow()
    expect(() => client.addItem(-1, 'menu')).toThrow()
    expect(fetcher).not.toHaveBeenCalled()
    await client.ensureStarted()
    fetcher.mockResolvedValueOnce(json({ ...dish, price: -10 }))
    await expect(client.getItem(101)).rejects.toThrow('Что-то пошло не так')
    fetcher.mockResolvedValueOnce(json({ ...cart, lines: [{ ...cart.lines[0], available: 'false' }] }))
    await expect(client.getCart()).rejects.toThrow('Что-то пошло не так')
  })

  it('TestFR20_mutations_publish_entire_validated_cart_and_are_serialized', async () => {
    const pending = deferred<Response>()
    const fetcher = vi.fn().mockResolvedValueOnce(json(menu)).mockImplementationOnce(() => pending.promise).mockResolvedValueOnce(json(emptyCart))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    await client.ensureStarted()
    const updates = vi.fn()
    client.onCartUpdate(updates)
    const added = client.addItem(101, 'menu')
    const removed = client.removeCartItem(101)
    await vi.waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
    const updated = { ...cart, lines: [{ ...cart.lines[0], available: false }], recommendation: rec }
    pending.resolve(json(updated))
    await added
    await removed
    expect(updates.mock.calls).toEqual([[updated], [emptyCart]])
    expect(client.getLastCart()).toEqual(emptyCart)
    expect(JSON.parse(fetcher.mock.calls[1][1].body)).toEqual({ item_id: 101, source: 'menu' })
  })

  it('TestAN02_429_drops_event_without_retry_or_duplicate_server_events', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(json(menu)).mockResolvedValue(new Response(null, { status: 429 }))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    const tracker = await import('./tracker')
    await client.ensureStarted()
    tracker.trackPageOpen()
    tracker.trackPageOpen()
    await vi.waitFor(() => expect(fetcher).toHaveBeenCalledTimes(2))
    expect(JSON.parse(fetcher.mock.calls[1][1].body)).toEqual({ name: 'page_open', payload: {} })
  })

  it('TestAN02_impressions_dedup_per_id_and_opening_feed_once_regardless_of_count', async () => {
    const fetcher = vi.fn().mockImplementation((url: string) => Promise.resolve(url.endsWith('/events') ? new Response(null, { status: 204 }) : json(menu)))
    vi.stubGlobal('fetch', fetcher)
    const client = await import('./client')
    const tracker = await import('./tracker')
    await client.ensureStarted()
    const first = tracker.nextImpressionScope()
    tracker.trackRecImpression(first, 'dish', 202, 'expert')
    tracker.trackRecImpression(first, 'dish', 202, 'heuristic')
    tracker.trackRecFeedVisible(first, 101, 13)
    tracker.trackRecFeedVisible(first, 101, 12)
    const reopen = tracker.nextImpressionScope()
    tracker.trackRecImpression(reopen, 'dish', 202, 'expert')
    tracker.trackRecFeedVisible(reopen, 101, 13)
    const cartScope = tracker.nextImpressionScope()
    tracker.trackRecImpression(cartScope, 'cart', 202, 'expert')
    tracker.trackRecImpression(cartScope, 'cart', 303, 'heuristic')
    tracker.trackRecImpression(cartScope, 'cart', 202, 'expert')
    const events = fetcher.mock.calls.filter(([url]) => url.endsWith('/events')).map((call) => JSON.parse(String((call as unknown as [string, RequestInit])[1].body)))
    expect(events.filter((event) => event.name === 'rec_impression')).toHaveLength(4)
    expect(events.filter((event) => event.name === 'rec_feed_visible')).toHaveLength(2)
    expect(events[1].payload.recs_count).toBe(13)
  })

  it('TestNFR04_response_validators_check_config_recs_totals_and_image_urls', async () => {
    const validation = await import('./validation')
    expect(validation.parseConfig(config)).toEqual(config)
    expect(() => validation.parseRecs({ recs: [{ ...rec, source: 'injected' }] })).toThrow()
    expect(() => validation.parseCart({ ...cart, total: 1 })).toThrow()
    expect(validation.parseItem({ ...dish, photo_url: 'javascript:alert(1)', photo_fallback: '//evil.test/x' }).photo_url).toBe('')
    for (const value of ['https://tildacdn.com.evil.test/x', 'https://user:pass@static.tildacdn.com/x', 'http://static.tildacdn.com/x', 'data:image/svg+xml,evil']) expect(validation.safeRemoteImage(value)).toBe('')
    for (const value of ['/static/../secret', '/static/\\evil', '/static/x?secret=y', '/static/%2e%2e/secret', '/static/%2f..%2fsecret', '/static/%5cevil', '/static/%00.png']) expect(validation.safeLocalImage(value)).toBe('')
  })
})

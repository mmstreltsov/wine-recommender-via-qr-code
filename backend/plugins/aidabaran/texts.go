const (
	fallbackFull  = "Блюдо «%s» задаёт характер перемены — «%s» отвечает контрастом текстур и ароматов, и стол складывается в цельную линию."
	fallbackShort = "«%s» и «%s»: контраст текстур и ароматов держит ритм трапезы."
	tinyTemplate  = "«%s» и «%s» — пара уравновешивает вкус и ритм стола."
)

func pairText(dishName, candName, fromCategory string) string {
	t, ok := reasonTemplates[fromCategory]
	if !ok {
		t = textTemplate{full: fallbackFull, short: fallbackShort}
	}
	full := fmt.Sprintf(t.full, dishName, candName)
	if utf8.RuneCountInString(full) <= reasonMaxLen {
		return full
	}
	short := fmt.Sprintf(t.short, dishName, candName)
	if utf8.RuneCountInString(short) <= reasonMaxLen {
		return short
	}
	return clampReason(fmt.Sprintf(tinyTemplate, dishName, candName))
}

func clampReason(s string) string {
	r := []rune(s)
	if len(r) <= reasonMaxLen {
		return s
	}
	return string(r[:reasonMaxLen])
}

func (e *engine) textFor(dish, cand domain.MenuItem) string {
	return pairText(dish.Name, cand.Name, e.catName[dish.CategoryID])
}

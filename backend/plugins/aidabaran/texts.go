func pairText(dishName, candName, fromCategory, toCategory string) string {
	t := templateFor(fromCategory, toCategory)
	full := fmt.Sprintf(t.full, dishName, candName)
	if utf8.RuneCountInString(full) <= reasonMaxLen {
		return full
	}
	short := fmt.Sprintf(t.short, dishName, candName)
	if utf8.RuneCountInString(short) <= reasonMaxLen {
		return short
	}
	// FR-11/12: preserve both names and the culinary reason, shortening only names.
	budget := reasonMaxLen - utf8.RuneCountInString(fmt.Sprintf(t.short, "", ""))
	dishLen, candLen := utf8.RuneCountInString(dishName), utf8.RuneCountInString(candName)
	dishLimit := budget / 2
	candLimit := budget - dishLimit
	if dishLen < dishLimit {
		candLimit = budget - dishLen
	} else if candLen < candLimit {
		dishLimit = budget - candLen
	}
	return fmt.Sprintf(t.short, shortenName(dishName, dishLimit), shortenName(candName, candLimit))
}

func shortenName(s string, limit int) string {
	r := []rune(s)
	if len(r) <= limit {
		return s
	}
	return string(r[:limit-1]) + "…"
}

func (e *engine) textFor(dish, cand domain.MenuItem) string {
	return pairText(dish.Name, cand.Name, e.catName[dish.CategoryID], e.catName[cand.CategoryID])
}
